"""Read the coach's XLSX without changing it; generate the browser exercise catalog.

Usage: python tools/import_exercises.py path/to/KILO_Exercise_Database_261023.xlsx
Uses only Python's standard library. Run again when the coach supplies an update.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET
from zipfile import ZipFile

NS = {"s": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
FIELDS = ["region", "category", "subcategory", "name", "video", "instructions",
          "novice", "intermediate", "advanced", "seriesA", "seriesB", "seriesCD",
          "videoLink", "notes"]
HEADERS = ["Regio", "Categorie", "Subcategorie", "Oefening", "Video", "Instructions",
           "Novice", "Intermediate", "Advanced", "A series", "B series", "C/D series",
           "Video link", "Notities"]


def read_catalog(source):
    with ZipFile(source) as archive:
        strings = []
        if "xl/sharedStrings.xml" in archive.namelist():
            for item in ET.fromstring(archive.read("xl/sharedStrings.xml")).findall("s:si", NS):
                strings.append("".join(text.text or "" for text in item.findall(".//s:t", NS)))
        relationships = ET.fromstring(archive.read("xl/_rels/workbook.xml.rels"))
        targets = {item.attrib["Id"]: item.attrib["Target"] for item in relationships}
        sheets = {}
        for sheet in ET.fromstring(archive.read("xl/workbook.xml")).findall("s:sheets/s:sheet", NS):
            relation = sheet.attrib["{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"]
            target = targets[relation]
            sheets[sheet.attrib["name"]] = target.lstrip("/") if target.startswith("/") else "xl/" + target

        def cells(sheet):
            result = {}
            for cell in ET.fromstring(archive.read(sheets[sheet])).findall(".//s:sheetData/s:row/s:c", NS):
                raw = cell.find("s:v", NS)
                value = raw.text if raw is not None else None
                if cell.get("t") == "s" and value is not None:
                    value = strings[int(value)]
                elif cell.get("t") == "inlineStr":
                    value = "".join(text.text or "" for text in cell.findall(".//s:t", NS))
                formula = cell.find("s:f", NS)
                if value is not None or formula is not None:
                    result[cell.attrib["r"]] = {"value": value}
                    if formula is not None:
                        result[cell.attrib["r"]]["formula"] = formula.text
            return result

        database = cells("Exercise Database")
        for index, expected in enumerate(HEADERS):
            actual = database.get(f"{chr(65 + index)}2", {}).get("value")
            if actual != expected:
                raise ValueError(f"Unexpected column {index + 1}: {actual!r}; expected {expected!r}")
        rows = sorted({int(address[1:]) for address in database if address.startswith("D") and int(address[1:]) >= 3})
        exercises = []
        for row in rows:
            values = {key: database.get(f"{chr(65 + index)}{row}", {}).get("value") for index, key in enumerate(FIELDS)}
            if not values["name"]:
                continue
            if len(values["name"]) > 100:
                raise ValueError(f"Exercise in row {row} exceeds CAP's 100-character name limit")
            exercises.append({"id": f"kilo-{row}", "sourceRow": row, **values})
        return {
            "source": {"filename": source.name, "sheet": "Exercise Database",
                       "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                       "columns": dict(zip(FIELDS, HEADERS))},
            "overview": cells("Overzicht"),
            "exercises": exercises,
        }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "frontend/js/exercise-data.js")
    args = parser.parse_args()
    catalog = read_catalog(args.source)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    # JSON remains data; Excel formulas/notes are never evaluated as browser code.
    data = json.dumps(catalog, ensure_ascii=True, separators=(",", ":"))
    args.output.write_text("// Generated by tools/import_exercises.py; edit the workbook, then re-import.\nwindow.capExerciseDatabase = " + data + ";\n", encoding="utf-8")
    print(f"Imported {len(catalog['exercises'])} exercise rows into {args.output.name}")
