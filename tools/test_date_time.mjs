import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const context = { window: {} };
vm.runInNewContext(readFileSync(new URL('../frontend/js/date-time.js', import.meta.url), 'utf8'), context);
const format = context.window.capDateTime;
assert.equal(format.date('2026-10-27'), '27/10/2026');
assert.equal(format.date('2026-01-01T23:30:00Z'), '02/01/2026');
assert.equal(format.time('2026-01-01T23:30:00Z'), '00:30');
assert.equal(format.time('2026-07-01T22:00:00Z'), '00:00');
assert.equal(format.time('2026-03-29T00:30:00Z'), '01:30');
assert.equal(format.time('2026-03-29T01:30:00Z'), '03:30');
assert.equal(format.time('2026-10-25T00:30:00Z'), '02:30');
assert.equal(format.time('2026-10-25T01:30:00Z'), '02:30');
assert.equal(format.dateTime('2026-10-27T17:45:00Z'), '27/10/2026 · 18:45');
assert.equal(format.parseDate('29/02/2028'), '2028-02-29');
assert.equal(format.parseDate('27102026'), '2026-10-27');
for (const value of ['29/02/2026', '31/04/2026', '01/13/2026', '', '2026-10-27']) assert.equal(format.parseDate(value), '');
assert.equal(format.parseTime('1830'), '18:30');
assert.equal(format.parseTime('00:00'), '00:00');
assert.equal(format.parseTime('23:59'), '23:59');
for (const value of ['24:00', '12:60', '6pm', '']) assert.equal(format.parseTime(value), '');
assert.equal(format.date('not-a-date'), '');
console.log('Belgian date/time checks passed: dd/mm/yyyy, 24h, midnight, both DST transitions and invalid input.');
