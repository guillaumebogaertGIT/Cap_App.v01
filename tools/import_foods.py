"""Import Calorietabel from Voedingsschema.xlsx without changing the workbook.

Usage: python tools/import_foods.py path/to/Voedingsschema.xlsx
Python standard library only; cached Excel kcal values are preserved.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import xml.etree.ElementTree as ET
from zipfile import ZipFile

NS = {"s": "http://schemas.openxmlformats.org/spreadsheetml/2006/main"}
FIELDS = ["name", "baseAmount", "unit", "calories", "proteinG", "carbsG", "fatG"]


def read_foods(source):
    with ZipFile(source) as archive:
        strings = []
        if "xl/sharedStrings.xml" in archive.namelist():
            strings = ["".join(t.text or "" for t in item.findall(".//s:t", NS)) for item in ET.fromstring(archive.read("xl/sharedStrings.xml")).findall("s:si", NS)]
        targets = {item.get("Id"): item.get("Target") for item in ET.fromstring(archive.read("xl/_rels/workbook.xml.rels"))}
        sheets = ET.fromstring(archive.read("xl/workbook.xml")).findall("s:sheets/s:sheet", NS)
        sheet = next(item for item in sheets if item.get("name") == "Calorietabel")
        target = targets[sheet.get("{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id")]
        path = target.lstrip("/") if target.startswith("/") else "xl/" + target
        cells = {}
        for cell in ET.fromstring(archive.read(path)).findall(".//s:sheetData/s:row/s:c", NS):
            raw = cell.find("s:v", NS)
            value = raw.text if raw is not None else None
            if cell.get("t") == "s" and value is not None:
                value = strings[int(value)]
            elif cell.get("t") == "inlineStr":
                value = "".join(t.text or "" for t in cell.findall(".//s:t", NS))
            cells[cell.get("r")] = value
        headers = [cells.get(f"{column}1") for column in "ABCDEFG"]
        if headers != ["Product", "Hoeveelheid", "Eenheid", "Kcal", "Eiwit", "Koolhydraten", "Vet"]:
            raise ValueError("Unexpected Calorietabel headers")
        foods = []
        for row in sorted(int(address[1:]) for address in cells if address.startswith("A") and int(address[1:]) > 1 and cells[address]):
            food = {"id": f"food-{row}", "sourceRow": row}
            for column, field in zip("ABCDEFG", FIELDS):
                value = cells.get(f"{column}{row}")
                if field not in ["name", "unit"]:
                    try:
                        value = float(value) if value is not None else None
                    except ValueError:
                        value = None
                food[field] = value
            food["complete"] = bool(food["unit"]) and all(isinstance(food[key], (int, float)) and math.isfinite(food[key]) and food[key] >= 0 for key in ["baseAmount", "calories", "proteinG", "carbsG", "fatG"]) and food["baseAmount"] > 0
            foods.append(food)
        return {"source": {"filename": source.name, "sheet": "Calorietabel", "sha256": hashlib.sha256(source.read_bytes()).hexdigest()}, "foods": foods}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    data = read_foods(args.source)
    output = Path(__file__).resolve().parents[1] / "frontend/js/food-data.js"
    output.write_text("// Generated by tools/import_foods.py.\nwindow.capFoodDatabase = " + json.dumps(data, ensure_ascii=True, separators=(",", ":"), allow_nan=False) + ";\n", encoding="utf-8")
    print(f"Imported {len(data['foods'])} foods; {sum(food['complete'] for food in data['foods'])} have complete nutrition data.")
